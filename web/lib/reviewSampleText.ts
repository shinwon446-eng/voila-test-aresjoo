// 샘플 후기의 말 조각. lib/reviewSamples.ts 만 이 파일을 읽는다.
// 실제 손님이 쓴 글이 아니다. 정식 서비스 전의 시험 사이트를 채우는 샘플이고, 정식 서비스에서는 꺼야 한다(스위치는 lib/reviewSamples.ts 머리에 적었다).
// 말투의 기준(2026-10-12 파운더): 다른 서비스 후기 화면의 손님들처럼 짧고 꾸밈없는 말. 그 화면의 별명과 글은 그대로 옮기지 않는다(BANNED 로 막는다).
// 조각에는 긴 줄표, 가운뎃점, 느낌표를 쓰지 않는다(tests/reviewSamples.test.ts 가 만든 글 전체를 검사한다).
// 조각은 서로 붙어도 말이 되게 쓴다: 한 조각은 한 가지만 말한다(나온 것, 물건, 배송, 쓰임, 맺음말).
// 조각마다 쓸 수 있는 조건을 줄 끝에 적는다(아래 Frag). 박스의 카테고리가 아니라 그 건의 상품과 결과와 별점을 보고 고른다.
// 넣지 않는 말: 또 열게 부추기거나 잃은 것을 되찾으려는 말(중독된다, 월급날 다시 온다, 될 때까지), 다시 열겠다거나 또 오겠다는 말, 다음 박스를 기다린다는 말.
//   별명에도 넣지 않는다. 아쉬운 결과 뒤에 다시 해 보겠다는 맺음말은 없다.

/**
 * 조각 한 줄: 글과 그 글을 쓸 수 있는 조건. 조건은 줄 끝에 낱말로 적고 L 이 떼어 낸다. 적지 않은 줄은 어느 건에나 쓴다.
 *   @이름  그 사실이 맞는 건에만 쓴다(여럿이면 모두 맞아야 한다).
 *     상품: @real 손에 받는 물건이다(디지털 상품이 아니다)  @parcel 택배 상자로 온다  @bulk 상자로 오지 않는 큰 것이다(차, 큰 가전)
 *           @made 정품, 마감, 품질을 말할 만한 공산품이다  @boxed 구성품이 든 제품 상자가 있다(전자제품, 가전)  @new 새 제품이라고 할 수 있다
 *           @sealed 밀봉된 채로 온다  @use 쓰는 물건이다  @gift 선물이 될 만하다
 *     결과: @money 받을 금액(상품가 × REFUND_RATE)이 박스 가격 이상이다. 낸 것보다 많이 받았다, 손해가 아니다 같은 말에 붙인다
 *           @par 받을 금액이 박스 가격의 100%에서 110% 사이다(PAR_BAND). 딱 본전, 본전치기, 박스값 정도 같은 말은 여기에만 쓴다
 *           @loss 받을 금액이 박스 가격에 못 미친다
 *           @large 상품가가 박스 가격의 1.5배 이상이다  @small 그 아래다  @common 그 박스에서 가장 흔한 상품이다
 *     별점: @r3 별 셋  @r4 별 넷  @r5 별 다섯. 점수를 말하는 줄(별 하나 뺐다, 10/10)에는 반드시 붙인다
 *   #이름  이 줄이 말하는 거리. 한 글에 같은 거리를 말하는 줄은 하나만 들어간다(반대말과 겹치는 말이 한 글에 들지 않는다).
 *     #pack 포장과 상자  #time 배송에 걸린 날  #wait 받기까지 기다린 날(상자로 오지 않는 큰 것)  #luck 나온 것이 아쉽다  #sum 돈 셈
 *     #who 누가 쓰는지  #recv 잘 받았다는 인사  #want 바라던 것인지
 *   ^이름  앞에서 그 거리를 말한 글에만 붙는다(여럿이면 하나만 맞아도 된다).
 * 적지 않아도 따라오는 것: #pack 과 #time 은 @parcel, #wait 는 @bulk, #recv 는 @real, @money 와 @par 와 @loss 는 #sum.
 * #sum 은 본전, 이득 같은 돈 이야기와 몇 번 열었다는 말에 붙인다: 모두 얼마를 썼는지 모르므로 둘을 한 글에 넣지 않는다.
 * 이 사이트에 없는 일은 적지 않는다(받는 길은 components/inventory 의 보관함이 정한다):
 *   디지털 상품에는 USDT로 받기만 있다. 코드를 보내 주거나 등록해 주는 흐름이 없으므로 받아서 썼다, 등록했다, 도착했다는 말을 하지 않는다.
 *   차와 큰 가전에도 배송 신청 말고 따로 정해 둔 인도, 설치, 수거, 서류 절차가 없다. 문의에 답하는 창구도 화면에 없다.
 */
export interface Frag { text: string; need: number; about: number; after: number }

const FACTS = ["real", "parcel", "bulk", "made", "boxed", "new", "sealed", "use", "gift", "money", "par", "loss", "large", "small", "common", "r3", "r4", "r5"];
const TALKS = ["pack", "time", "wait", "luck", "sum", "who", "recv", "want"];
const bitsOf = (list: string[], names: string): number => names.split(" ").filter(Boolean).reduce((bits, name) => {
  const k = list.indexOf(name);
  if (k < 0) throw new Error("reviewSampleText: 모르는 조건 " + name);
  return bits | (1 << k);
}, 0);
/** 사실의 이름들을 비트로("parcel boxed") */
export const fact = (names: string): number => bitsOf(FACTS, names);
/** 거리의 이름들을 비트로("pack time") */
export const talk = (names: string): number => bitsOf(TALKS, names);
/** 받는 과정을 말하는 거리: 포장, 배송에 걸린 날, 받기까지 기다린 날 */
export const ARRIVAL = talk("pack time wait");
/** 본전이라는 말의 띠: 받을 금액을 박스 가격으로 나눈 값이 이 사이일 때만 딱 본전, 본전치기라고 한다. 50달러 박스에서 66.50달러를 받은 건은 본전이 아니다 */
export const PAR_BAND: [number, number] = [1, 1.1];

const TAG = /^[@#^][a-z0-9]+$/;
function fragOf(line: string): Frag {
  const words = line.split(/\s+/).filter(Boolean);
  let need = 0, about = 0, after = 0;
  while (words.length > 1 && TAG.test(words[words.length - 1])) {
    const word = words.pop()!;
    if (word[0] === "@") need |= fact(word.slice(1)); else if (word[0] === "#") about |= talk(word.slice(1)); else after |= talk(word.slice(1));
  }
  if (about & talk("pack time")) need |= fact("parcel");
  if (about & talk("wait")) need |= fact("bulk");
  if (about & talk("recv")) need |= fact("real");
  if (need & fact("money par loss")) about |= talk("sum");
  return { text: words.join(" "), need, about, after };
}
/** 한 줄에 한 조각. every 는 그 묶음의 모든 줄에 붙는 조건이다 */
const L = (text: string, every = ""): Frag[] => text.split("\n").map((line) => line.trim()).filter(Boolean).map((line) => fragOf(line + " " + every));

